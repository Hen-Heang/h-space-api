-- H-Vault (docs/vault-design.md). Everything here is encrypted in the
-- browser; the server only ever stores and returns ciphertext. There are no
-- plaintext columns about the saved accounts at all.
--
-- Envelope format (base64, standard alphabet):
--   v2.<12-byte IV: 16 chars>.<AES-GCM ciphertext + 16-byte tag>
-- A wrapped vault key is 32 bytes + tag = 48 bytes = exactly 64 chars.

-- One per user: wrapped copies of the random vault key, plus the public KDF
-- settings the browser needs to unwrap it. A row present = vault set up.
CREATE TABLE vault_keysets (
    user_id              UUID PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    kdf                  VARCHAR(32)  NOT NULL CHECK (kdf IN ('PBKDF2-SHA256')),
    kdf_iterations       INTEGER      NOT NULL CHECK (kdf_iterations BETWEEN 600000 AND 10000000),
    kdf_salt             VARCHAR(24)  NOT NULL CHECK (kdf_salt ~ '^[A-Za-z0-9+/]{22}==$'),
    -- vault key under the master-password KEK
    wrapped_key          VARCHAR(84)  NOT NULL
        CHECK (wrapped_key ~ '^v2\.[A-Za-z0-9+/]{16}\.[A-Za-z0-9+/]{64}$'),
    -- vault key under the recovery-key KEK
    recovery_wrapped_key VARCHAR(84)  NOT NULL
        CHECK (recovery_wrapped_key ~ '^v2\.[A-Za-z0-9+/]{16}\.[A-Za-z0-9+/]{64}$'),
    created_at           TIMESTAMPTZ  NOT NULL,
    updated_at           TIMESTAMPTZ  NOT NULL,
    version              BIGINT       NOT NULL DEFAULT 0
);

-- One per saved account. The id is generated by the browser, because it's
-- part of the ciphertext's associated data (binds the payload to its row).
CREATE TABLE vault_items (
    id                 UUID PRIMARY KEY,
    user_id            UUID           NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    payload_ciphertext VARCHAR(16384) NOT NULL
        CHECK (payload_ciphertext ~ '^v2\.[A-Za-z0-9+/]{16}\.[A-Za-z0-9+/]{24,}={0,2}$'),
    created_at         TIMESTAMPTZ    NOT NULL,
    updated_at         TIMESTAMPTZ    NOT NULL,
    version            BIGINT         NOT NULL DEFAULT 0
);

CREATE INDEX idx_vault_items_user_updated ON vault_items (user_id, updated_at DESC);
